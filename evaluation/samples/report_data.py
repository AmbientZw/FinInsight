def render_report(report: dict) -> str:
    """将研报参数渲染为带页码标注的完整文本。"""
    lines = []

    # 第1页：标题 + 行业概况
    lines.append(f"[第1页] {report['title']}")
    lines.append(f"[第1页] （模拟研报，数据为虚构，仅用于评测）")
    lines.append(f"[第1页] {report['overview']}")

    # 第2页：市场规模
    lines.append(f"[第2页] 市场规模：{report['market_size']}")

    # 第3页：竞争格局
    lines.append(f"[第3页] 竞争格局：{report['competition']}")

    # 第4页：核心财务数据
    lines.append("[第4页] 核心财务与业务数据：")
    for i, f in enumerate(report["financials"]):
        lines.append(f"[第4页] {i+1}. {f}")

    # 第5页：驱动因素
    lines.append("[第5页] 增长驱动因素：")
    for i, d in enumerate(report["drivers"]):
        lines.append(f"[第5页] {i+1}. {d}")

    # 第6页：主要风险
    lines.append("[第6页] 主要风险提示：")
    for i, r in enumerate(report["risks"]):
        lines.append(f"[第6页] {i+1}. {r}")

    # 第7页：投资建议
    lines.append("[第7页] 投资建议：")
    for i, a in enumerate(report["advice"]):
        lines.append(f"[第7页] {i+1}. {a}")

    # 第8页：需核实疑点
    lines.append("[第8页] 需进一步核实的疑点：")
    lines.append(f"[第8页] {report['verify']}")

    # 难例：矛盾数据单独成段（分散在不同位置）
    if report.get("contradiction"):
        lines.append(f"[第9页] （补充说明）{report['contradiction']}")

    return "\n".join(lines)
